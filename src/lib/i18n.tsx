export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = React.useState<Lang>("sl");

  React.useEffect(() => {
    // Globoka povezava z jezikom: /?lang=de ali /?exhibit=…&lang=it —
    // nemški ali italijanski portal tako poveže neposredno v svoj jezik
    // (prednost pred shranjeno izbiro, enako kot pri razstavnih povezavah).
    const urlLang = new URLSearchParams(window.location.search).get("lang") as Lang | null;
    if (urlLang && LANG_CODES.includes(urlLang)) {
      setLangState(urlLang);
      window.localStorage.setItem("mvg-lang", urlLang);
      return;
    }
    const stored = window.localStorage.getItem("mvg-lang") as Lang | null;
    if (stored && LANG_CODES.includes(stored)) setLangState(stored);
  }, []);

  React.useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);

  // Izbira jezika se sinhronizira med zavihki istega brskalnika
  // (dogodek `storage` — enak mehanizem kot pri obiskih in sprehodih).
  React.useEffect(() => {
    const onStorage = (event: StorageEvent) => {
      if (
        event.key === "mvg-lang" &&
        event.newValue &&
        LANG_CODES.includes(event.newValue as Lang)
      ) {
        setLangState(event.newValue as Lang);
      }
    };
    window.addEventListener("storage", onStorage);
    return () => window.removeEventListener("storage", onStorage);
  }, []);

  const setLang = React.useCallback((next: Lang) => {
    setLangState(next);
    window.localStorage.setItem("mvg-lang", next);
  }, []);

  const value = React.useMemo(
    () => ({ lang, setLang, t: ui[lang] as UiDict }),
    [lang, setLang]
  );

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLang() {
  return React.useContext(LanguageContext);
}

/**
 * Izbira jezikovno specifičnega polja iz zapisa (titleSi / titleEn …).
 * Hrvaščina bere slovensko vsebino (medsebojna razumljivost ob Kolpi),
 * nemščina in italijanščina pa angleško — vsebina zbirk ostaja v
 * izvirniku, vmesnik je polno preveden.
 */
export function pick<T>(lang: Lang, si: T, en: T): T {
  return lang === "sl" || lang === "hr" ? si : en;
}

/** Vsi podprti jeziki muzeja (vrstni red stikala). */
export const LANG_CODES: Lang[] = ["sl", "hr", "en", "de", "it"];

